const { test } = require('node:test')
const assert = require('node:assert/strict')
const path = require('node:path')

const http = require('node:http')
const playwrightPath = process.env.PLAYWRIGHT_MODULE || path.resolve(__dirname, '../../../product-scrapping-bundle/node_modules/playwright')
const { chromium } = require(playwrightPath)
const { setup, headers } = require('./fake-sheets.cjs')

async function withBrowser(t, run) {
  const { handler, tabs } = setup()
  const app = require('express')()
  app.use(require('express').text({ type: '*/*' }))
  app.all('/api/records', async (req, res) => {
    const response = await handler({ httpMethod: req.method, body: req.body })
    res.status(response.statusCode).type('json').send(response.body)
  })
  app.get('/api/earnings', (req, res) => res.json({ records: [] }))
  app.use(require('express').static(path.resolve(__dirname, '../public')))
  const server = http.createServer(app)
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  t.after(() => new Promise(resolve => server.close(resolve)))
  const browser = await chromium.launch({ headless: true })
  t.after(() => browser.close())
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', async route => {
    const url = route.request().url()
    if (url.startsWith(`http://127.0.0.1:${server.address().port}/`)) return route.continue()
    if (url === 'https://d3js.org/d3.v7.min.js') return route.fulfill({ path: path.join(__dirname, 'fixtures/d3.v7.min.js'), contentType: 'text/javascript' })
    if (url.includes('d3-sankey')) return route.fulfill({ path: path.join(__dirname, 'fixtures/d3-sankey.min.js'), contentType: 'text/javascript' })
    return route.abort()
  })
  await page.goto(`http://127.0.0.1:${server.address().port}`)
  await page.waitForFunction(() => !document.querySelector('#empty-msg').hidden)
  await run({ page, tabs })
  assert.deepEqual(errors, [])
}

test('browser: required category and optional note submit and survive reload', async t => withBrowser(t, async ({ page, tabs }) => {
  assert.equal(await page.locator('#category').count(), 1, 'category dropdown exists')
  assert.deepEqual(await page.locator('#category option').allTextContents(), ['Choose a category…', 'Food & Drinks', 'Transportation', 'Groceries', 'Shopping', 'Bills', 'Health', 'Entertainment', 'Family & Gifts', 'Transfers', 'Other'])
  assert.equal(await page.locator('#category').getAttribute('required'), '')
  await page.locator('#amount').fill('10')
  await page.locator('#add-form button').click()
  assert.equal(tabs['All Data'].length, 1)
  assert.equal(await page.locator('#category').evaluate(el => el.validity.valueMissing), true)
  await page.locator('#category').selectOption('Food & Drinks')
  await page.locator('#add-form button').click()
  await page.waitForFunction(() => document.querySelector('#form-msg').textContent === 'Spending added.')
  assert.equal(tabs['All Data'][1][2], '')
  assert.equal(tabs['All Data'][1][3], 'Food & Drinks')
  assert.equal(await page.locator('#category').inputValue(), '')
  await page.reload()
  await page.waitForFunction(() => document.querySelector('#sum-today').textContent === '$10.00')
  assert.match(await page.locator('#sankey').textContent(), /Food & Drinks.*\$10.00/)
}))

test('browser: category groups and search, transfers visible but excluded from expenses', async t => withBrowser(t, async ({ page, tabs }) => {
  const date = await page.evaluate(() => localStamp())
  tabs['All Data'].push([10, date, 'Lunch', 'Food & Drinks'], [20, date, 'Dinner', 'Food & Drinks'], [5, date, 'Legacy note'], [100, date, 'Bank move <b>safe</b>', 'Transfers'])
  await page.reload()
  await page.waitForFunction(() => document.querySelector('#sum-today').textContent !== '$0.00')
  for (const id of ['sum-today', 'sum-week', 'sum-month']) assert.equal(await page.locator('#' + id).textContent(), '$35.00')
  const chart = await page.locator('#sankey').textContent()
  assert.match(chart, /Food & Drinks.*\$30.00/)
  assert.match(chart, /Other.*\$5.00/)
  assert.doesNotMatch(chart, /Lunch|Dinner|Transfers|\$100.00/)
  assert.match(await page.locator('#transfer-summary').textContent(), /\$100.00/)
  assert.match(await page.locator('#transfer-list').textContent(), /Bank move <b>safe<\/b>/)
  assert.equal(await page.locator('#transfer-list b').count(), 0)
  await page.locator('#search').fill('food & drinks')
  assert.match(await page.locator('#sankey').textContent(), /\$30.00/)
  assert.doesNotMatch(await page.locator('#sankey').textContent(), /Other/)
  await page.locator('#search').fill('lunch')
  assert.match(await page.locator('#sankey').textContent(), /\$10.00/)
  await page.locator('#search').fill('transfers')
  assert.equal(await page.locator('#sankey').textContent(), '')
  assert.match(await page.locator('#transfer-summary').textContent(), /\$100.00/)
  await page.locator('#search').fill('bank move')
  assert.match(await page.locator('#transfer-list').textContent(), /Bank move/)
  await page.locator('#month-filter').fill('2000-01')
  assert.equal(await page.locator('#transfer-list li').count(), 0)
  assert.match(await page.locator('#transfer-summary').textContent(), /\$0.00/)
}))
